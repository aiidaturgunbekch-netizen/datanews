/**
 * Что открыть поверх публичного сайта по адресу. По умолчанию — ничего: публичная главная страница.
 *  - #admin   — панель управления (только с паролем администратора; права проверяет сервер);
 *  - #login   — вход в личный кабинет;
 *  - #cabinet — личный кабинет (без входа покажет форму входа).
 * Адрес сам по себе прав не даёт: без сеанса администратора панель показывает только форму входа,
 * а все данные панели сервер отдаёт только администратору.
 */
export type Screen = 'home' | 'admin' | 'login' | 'cabinet';

export const screenFromHash = (hash: string): Screen => {
  const h = hash.replace(/^#/, '').toLowerCase();
  if (h === 'admin') return 'admin';
  if (h === 'login') return 'login';
  if (h === 'cabinet') return 'cabinet';
  return 'home';
};

/** Адрес для экрана — чтобы вход и кабинет открывались по ссылке и закрывались кнопкой «Назад» */
export const hashFor = (s: Screen) => (s === 'home' ? '' : `#${s}`);
